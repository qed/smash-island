// ============================================================================
//  trace-hurtboxes.mjs — every fighter's hurtbox, traced from their own render
// ============================================================================
// "the hurtboxes and hitboxes should be their actual shape and size, not an approximation." A fighter used
// to be hit as an ellipse sized from their art box. This traces the render itself: the PNG's alpha, sliced
// into BANDS horizontal bands, each band's leftmost and rightmost opaque pixel, joined into one polygon
// (down the right side, back up the left). The points are written in FIGHTER SPACE -- pixels relative to
// (f.x, f.y), in the exact contain-fit the renderer uses (see drawFighter: dh = min(imgH*R, imgW*R/ar),
// feet on R+12) -- so hurtGap needs no image at run time, only this table and the fighter's facing.
//
// A fighter with no render keeps their ellipse (HURTBOX). The block it writes is GENERATED: edit this
// script, not the table.
//
//   node scripts/trace-hurtboxes.mjs            (cwd = repo root; rewrites artifacts/V1/index.html)
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';
import { loadMonolith } from '../test/helpers/load-monolith.js';

const HTML = 'artifacts/V1/index.html';
const BANDS = 22;            // horizontal slices: 200px renders, ~9px a band, ~3px on screen
const ALPHA = 40;            // below this the pixel is air (fetch-sprites erases the halo under 24)
const R = 24;                // f.r: every fighter's body radius; the fit depends on it and nothing else
const FEET = R + 12;         // where the render's bottom lands (drawFighter)

const w = loadMonolith().window;
const roster = w.eval('ROSTER.filter(function(r){ return r.play; }).map(function(r){ var s = SPRITES[r.name] || {}; return { name:r.name, src:s.src||null, imgH:s.imgH==null?2.8:s.imgH, imgW:s.imgW==null?2.3:s.imgW, flip:!!s.flip }; })');

function trace(png) {
  const { width: W, height: H, data } = png;
  const right = [], left = [];
  for (let b = 0; b < BANDS; b++) {
    const y0 = Math.floor(b * H / BANDS), y1 = Math.max(y0 + 1, Math.floor((b + 1) * H / BANDS));
    let lo = W, hi = -1;
    for (let y = y0; y < y1; y++) for (let x = 0; x < W; x++) if (data[(y * W + x) * 4 + 3] >= ALPHA) { if (x < lo) lo = x; if (x > hi) hi = x; }
    if (hi < 0) continue;                      // an empty band (above the head, between legs) is skipped
    const yc = (y0 + y1) / 2;
    right.push([hi + 1, yc]); left.push([lo, yc]);
  }
  // close the top and bottom with the first and last bands' extents, so the polygon has flat caps
  const pts = [];
  if (right.length) {
    pts.push([left[0][0], right[0][1] - (H / BANDS) / 2]);
    pts.push([right[0][0], right[0][1] - (H / BANDS) / 2]);
    for (const p of right) pts.push(p);
    pts.push([right[right.length - 1][0], right[right.length - 1][1] + (H / BANDS) / 2]);
    pts.push([left[left.length - 1][0], left[left.length - 1][1] + (H / BANDS) / 2]);
    for (let i = left.length - 1; i >= 0; i--) pts.push(left[i]);
  }
  return { pts, W, H };
}

const rows = [];
let missing = [];
for (const r of roster) {
  if (!r.src) { missing.push(r.name); continue; }
  const png = PNG.sync.read(readFileSync('artifacts/V1/' + r.src));
  const { pts, W, H } = trace(png);
  const ar = W / H;
  const dh = Math.min(r.imgH * R, (r.imgW * R) / ar), dw = dh * ar;
  // image pixel -> fighter space: x centred, y so the bottom row sits on FEET
  const out = pts.map(([px, py]) => [+((px / W - 0.5) * dw).toFixed(1), +(FEET - dh + (py / H) * dh).toFixed(1)]);
  rows.push(`  ${JSON.stringify(r.name)}: ${JSON.stringify(out.flat())},`);
}
const block = `// GENERATED by scripts/trace-hurtboxes.mjs -- do not edit by hand. Each fighter's hurtbox polygon, traced from
// their render's alpha in ${BANDS} horizontal bands, in fighter-space pixels relative to (f.x, f.y), drawn as the
// renderer fits the image (feet on R+12). Stored facing the way the PNG faces; hurtGap mirrors it with the fighter.
const HURT_POLY = {
${rows.join('\n')}
};
// END GENERATED (HURT_POLY)`;

let html = readFileSync(HTML, 'utf8');
const start = html.indexOf('// GENERATED by scripts/trace-hurtboxes.mjs'), end = html.indexOf('// END GENERATED (HURT_POLY)');
if (start >= 0 && end > start) {
  html = html.slice(0, start) + block + html.slice(end + '// END GENERATED (HURT_POLY)'.length);
} else {
  const anchor = 'const HURT_R0 = 24;';
  if (!html.includes(anchor)) throw new Error('anchor not found');
  html = html.replace(anchor, block.replace(/\n/g, '\r\n') + '\r\n' + anchor);
}
writeFileSync(HTML, html);
console.log(`${rows.length} fighters traced, ${missing.length} without a render${missing.length ? ': ' + missing.join(', ') : ''}`);
try { w.close(); } catch {}
